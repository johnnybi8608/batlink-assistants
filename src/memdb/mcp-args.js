// Command-line arguments that attach the memory tools to an AI session. The identity is derived from the waker
// entry and baked into the MCP bridge's launch arguments, so the AI cannot change it.

import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PORT, API_TOKEN_FILE } from '../local.js';

// Unique MCP server name: must not clash with any other "memdb" server the user has configured globally
export const MCP_NAME = 'batlink_memdb';

const MEM_MCP = join(resolve(dirname(fileURLToPath(import.meta.url)), '..', '..'), 'bin', 'mem-mcp.js');

/** Waker entry -> memory identity; the mail bot gets no memory tools (returns null) */
export function memIdentity(waker) {
  if (waker.engine === 'mailbot') return null;
  if (waker.kind === 'chat') return { actor: waker.agent, role: 'chat' };
  // Restricted persona DM (engine=persona: web search + memory only). Default role 'chat'; an assistant serving a
  // family member sets memRole 'family-assistant' (no work data) and memSelf = that person's name or entity id.
  if (waker.engine === 'persona') return { actor: waker.agent, role: waker.memRole ?? 'chat', self: waker.memSelf ?? null };
  if (waker.kind === 'dm') return { actor: `${waker.agent}@dm`, role: waker.memRole ?? 'assistant', self: waker.memSelf ?? null };
  return { actor: `${waker.agent}@${waker.project}`, role: 'project', project: waker.project };
}

/**
 * Whether this waker's assistant gets the reminder tools (mem_reminder_*): persona assistants always do; any other
 * waker can opt in with "reminders": true (or out with false) in config.json. See REMINDER_AGENTS in tools.js.
 */
export function remindersEnabled(waker) {
  return waker.reminders ?? waker.engine === 'persona';
}

function mcpArgv(identity, waker) {
  // --port / --token-file: the MCP host may not pass our environment through, so they are given explicitly
  const argv = [MEM_MCP, '--actor', identity.actor, '--role', identity.role, '--port', String(PORT), '--token-file', API_TOKEN_FILE];
  if (identity.project) argv.push('--project', identity.project);
  if (identity.self) argv.push('--self', identity.self);
  if (remindersEnabled(waker)) argv.push('--reminders');
  return argv;
}

/** claude: add the memory server via --mcp-config (under its own name, next to any servers the user has) */
export function claudeMemArgs(waker) {
  const id = memIdentity(waker);
  if (!id) return [];
  return ['--mcp-config', JSON.stringify({ mcpServers: { [MCP_NAME]: { command: process.execPath, args: mcpArgv(id, waker) } } })];
}

/** codex: add an MCP server for this run with -c (does not modify ~/.codex/config.toml) */
export function codexMemArgs(waker) {
  const id = memIdentity(waker);
  if (!id) return [];
  return [
    '-c', `mcp_servers.${MCP_NAME}.command=${JSON.stringify(process.execPath)}`,
    '-c', `mcp_servers.${MCP_NAME}.args=${JSON.stringify(mcpArgv(id, waker))}`,
    // In exec mode nobody can click "allow", so MCP tools would be blocked; approve this server's tools
    // (permission checks happen in the main process)
    '-c', `mcp_servers.${MCP_NAME}.default_tools_approval_mode="approve"`
  ];
}

/** grok: reads MCP servers from .grok/config.toml in its working directory; this generates that file (identity still fixed in the launch arguments) */
export function grokMemToml(waker) {
  const id = memIdentity(waker);
  if (!id) return '';
  return `# Generated by src/memdb/mcp-args.js; overwritten before every wake-up\n[mcp_servers.${MCP_NAME}]\ncommand = ${JSON.stringify(process.execPath)}\nargs = ${JSON.stringify(mcpArgv(id, waker))}\n`;
}
